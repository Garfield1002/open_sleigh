SHAPE_3 = {"XmmReg1,vexVVVV_XmmReg,XmmReg2_m128", "YmmReg1,vexVVVV_YmmReg,YmmReg2_m256"}
SHAPE_2 = {"XmmReg1,XmmReg2_m128", "YmmReg1,YmmReg2_m256"}


def constructor_128(name: str, operands: str, pattern: str, macro: str, arity: int) -> str:
    pattern = pattern.replace("(XmmReg1 & ZmmReg1)", "(XmmReg1 & YmmReg1)")
    src1 = "vexVVVV_XmmReg" if arity == 2 else None
    calls = []
    for lane, off in ((0, 0), (1, 64)):
        args = [f"YmmReg1[{off},64]"]
        if src1:
            args.append(f"{src1}[{off},64]")
        args.append(f"m[{off},64]")
        calls.append(f"    {macro}({', '.join(args)});")
    body = "    local m:16 = XmmReg2_m128;\n" + "\n".join(calls) + "\n    avx_zero_upper(YmmReg1);"
    return f":{name} {operands} is {pattern}\n{{\n{body}\n}}\n"


def constructor_256(name: str, operands: str, pattern: str, macro: str, arity: int) -> str:
    # Read the source halves through the half-width subtables; keep the full
    # operand in the display and in the pattern so disassembly is unchanged.
    pattern = pattern.replace("(YmmReg1 & ZmmReg1) ... & YmmReg2_m256",
                              "(YmmReg1 & YmmReg2_m256) ... & YmmReg2_m256_L & YmmReg2_m256_H")
    if arity == 2:
        pattern = pattern.replace("& vexVVVV_YmmReg;",
                                  "& vexVVVV_YmmReg & vexVVVV_YmmReg_L & vexVVVV_YmmReg_H;")
    assert "YmmReg2_m256_L" in pattern, (name, pattern)
    calls = []
    for off, half, hoff in ((0, "lo", 0), (64, "lo", 64), (128, "hi", 0), (192, "hi", 64)):
        args = [f"YmmReg1[{off},64]"]
        if arity == 2:
            v = "vexVVVV_YmmReg_L" if half == "lo" else "vexVVVV_YmmReg_H"
            args.append(f"{v}[{hoff},64]")
        args.append(f"{half}[{hoff},64]")
        calls.append(f"    {macro}({', '.join(args)});")
    body = "    local lo:16 = YmmReg2_m256_L;\n    local hi:16 = YmmReg2_m256_H;\n" + "\n".join(calls)
    return f":{name} {operands} is {pattern}\n{{\n{body}\n}}\n"


def packed_file(inventory: list[dict]) -> tuple[str, set[str]]:
    out = [
        "#@family avx\n"
        "# The regular three-operand packed AVX and AVX2 forms, on 64-bit lanes.\n"
        "# Generated by scripts/avx_gen.py; do not edit. The lane macros live in\n"
        "# avx_macros.sinc, the half-width operands in avx_operands.sinc, and the\n"
        "# irregular instructions in avx_manual.sinc / avx2_manual.sinc.\n\n"
    ]
    done: set[str] = set()
    seen_headers: set[str] = set()
    for row in inventory:
        name = row["name"]
        if name not in TABLE:
            continue
        macro, arity = TABLE[name]
        shape = re.sub(r"\s+", "", row["operands"])
        expect = SHAPE_3 if arity == 2 else SHAPE_2
        if shape not in expect:
            continue
        key = (name, shape)
        if key in seen_headers:
            continue
        seen_headers.add(key)
        gen = constructor_128 if shape.startswith("Xmm") else constructor_256
        out.append(f"# {name}\n")
        out.append(gen(name, row["operands"], row["pattern"], macro, arity))
        out.append("\n")
        done.add(name)
    return "".join(out), done


def main() -> int:
    inventory = json.loads(INVENTORY.read_text())
    (X86 / "avx_macros.sinc").write_text(macro_library())
    packed, done = packed_file(inventory)
    (X86 / "avx.sinc").write_text(packed)
    (X86 / "avx2.sinc").write_text(
        "#@family avx\n"
        "# Reserved for AVX2-only forms that need their own file. The 256-bit\n"
        "# integer forms are generated into avx.sinc beside their 128-bit\n"
        "# siblings. Generated by scripts/avx_gen.py; do not edit.\n"
    )
    missing = sorted(set(TABLE) - done)
    if missing:
        print("no inventory match for:", " ".join(missing), file=sys.stderr)
    print(f"generated {len(done)} mnemonics")
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
